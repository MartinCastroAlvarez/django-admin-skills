def render_skill(
    graph: AdminGraph,
    *,
    name: str,
    options: SkillOptions | None = None,
    app_labels: Iterable[str] | None = None,
) -> SkillBundle:
    """Render ``graph`` into one skill called ``name``.

    :param name: the skill's ``name`` (and folder name) — validated against
        the Agent Skills rules.
    :param options: interfaces and URLs to document (defaults: REST + MCP,
        origin read from ``$DJANGO_ADMIN_URL``).
    :param app_labels: only document these apps (the graph itself may hold more).
    """
    validate_skill_name(name)
    options = options or SkillOptions()
    models = _models(graph, app_labels)
    known = {m.label for m in models}
    files: dict[str, str] = {"SKILL.md": _skill_md(name, graph, models, options)}
    for m in models:
        files[m.ref] = _reference(name, m, graph, known, options)
    return SkillBundle(name=name, files=dict(sorted(files.items())))


def render_skills_per_app(
    graph: AdminGraph,
    *,
    prefix: str = "admin",
    options: SkillOptions | None = None,
    app_labels: Iterable[str] | None = None,
) -> tuple[SkillBundle, ...]:
    """One skill per app, named ``<prefix>-<app_label>`` (underscores → hyphens)."""
    labels = sorted({m.app_label for m in _models(graph, app_labels)})
    bundles = []
    for label in labels:
        name = f"{prefix}-{label.replace('_', '-')}".strip("-")
        while "--" in name:
            name = name.replace("--", "-")
        bundles.append(render_skill(graph, name=name, options=options, app_labels=[label]))
    return tuple(bundles)
