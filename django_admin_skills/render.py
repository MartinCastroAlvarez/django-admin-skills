"""Render an :class:`~django_admin_graph.AdminGraph` into an Agent Skill.

This module is pure: it takes a graph (built by ``django_admin_graph.build_graph``
or read back with ``AdminGraph.from_dict``) and returns text. It never
imports a model, never touches an ``AdminSite`` and never queries the
database — the graph is the only source of truth, so a skill can be
generated from a saved JSON file in CI without the Django project.

Output layout (`Agent Skills <https://agentskills.io/specification>`_)::

    <name>/
    ├── SKILL.md                       — frontmatter + what the agent may do + how to call
    └── references/
        └── <app_label>.<model>.md     — one per model: fields, choices, relations,
                                         changelist, forms, actions, inlines

Every author-controlled string is passed through :mod:`django_admin_skills.sanitize`
and rendered as a quoted code span; identifiers are validated and anything
that does not look like one is dropped.
"""

from __future__ import annotations

from collections.abc import Iterable
from collections.abc import Mapping
from dataclasses import dataclass
from dataclasses import field

from django_admin_graph.schema import ActionInfo
from django_admin_graph.schema import AdminGraph
from django_admin_graph.schema import AdminNode
from django_admin_graph.schema import FieldInfo
from django_admin_graph.schema import InlineNode
from django_admin_graph.schema import ModelNode
from django_admin_graph.schema import Permissions

from django_admin_skills import sanitize
from django_admin_skills.options import SkillOptions
from django_admin_skills.options import validate_skill_name
from django_admin_skills.sanitize import code
from django_admin_skills.sanitize import quote

GENERATOR = "django-admin-skills"
#: First line of every generated SKILL.md body; ``write_skill`` refuses to
#: overwrite a SKILL.md that lacks it (a hand-written skill).
MARKER = f"<!-- generated by {GENERATOR}; do not edit, regenerate with `manage.py admin_skills` -->"

DESCRIPTION_LIMIT = 1024
_DEFAULT_HEADER = "Django administration"
_MAX_MODELS_IN_DESCRIPTION = 12

