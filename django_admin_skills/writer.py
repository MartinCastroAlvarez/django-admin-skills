"""Write a :class:`~django_admin_skills.render.SkillBundle` to disk, or check it.

Writing is confined to the skill folder: every path is validated as a
relative POSIX path with no ``..`` and is resolved inside ``out_dir``.
Stale ``references/*.md`` files from an earlier run are removed, and a
``SKILL.md`` that this package did not generate is never overwritten.
"""

from __future__ import annotations

import os
from pathlib import Path
from pathlib import PurePosixPath

from django_admin_skills.render import MARKER
from django_admin_skills.render import SkillBundle


class SkillWriteError(Exception):
    """The bundle cannot be written safely to the requested folder."""


def _safe_path(root: Path, rel: str) -> Path:
    pure = PurePosixPath(rel)
    if pure.is_absolute() or ".." in pure.parts or not pure.parts or "\\" in rel:
        raise SkillWriteError(f"Refusing unsafe path in bundle: {rel!r}")
    target = (root / Path(*pure.parts)).resolve()
    if root != target and root not in target.parents:
        raise SkillWriteError(f"Refusing path outside the skill folder: {rel!r}")
    return target


def _owned(root: Path) -> list[str]:
    """Files under ``root`` this generator owns: SKILL.md + references/*.md."""
    found: list[str] = []
    if (root / "SKILL.md").is_file():
        found.append("SKILL.md")
    refs = root / "references"
    if refs.is_dir():
        found += sorted(f"references/{p.name}" for p in refs.glob("*.md") if p.is_file())
    return found


def _check_name(bundle: SkillBundle, root: Path) -> None:
    if root.name != bundle.name:
        raise SkillWriteError(
            f"The skill folder must be named after the skill: {root.name!r} != {bundle.name!r} "
            "(Agent Skills require name == directory name)."
        )


def write_skill(bundle: SkillBundle, out_dir: str | os.PathLike[str]) -> list[str]:
    """Write ``bundle`` into ``out_dir`` (created if needed).

    Returns the relative paths that were created, changed or removed.
    """
    root = Path(out_dir).resolve()
    _check_name(bundle, root)
    existing = root / "SKILL.md"
    if existing.is_file() and MARKER not in existing.read_text(encoding="utf-8"):
        raise SkillWriteError(
            f"{existing} was not generated by django-admin-skills; refusing to overwrite it."
        )
    root.mkdir(parents=True, exist_ok=True)
    changed: list[str] = []
    for rel, text in bundle.files.items():
        target = _safe_path(root, rel)
        if target.is_file() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        changed.append(rel)
    for rel in _owned(root):
        if rel not in bundle.files:
            path = _safe_path(root, rel)
            if MARKER in path.read_text(encoding="utf-8"):
                path.unlink()
                changed.append(rel)
    return sorted(changed)


def check_skill(bundle: SkillBundle, out_dir: str | os.PathLike[str]) -> list[str]:
    """Compare ``bundle`` with ``out_dir``; return human-readable problems (empty = fresh)."""
    root = Path(out_dir).resolve()
    problems: list[str] = []
    if root.name != bundle.name:
        problems.append(f"folder {root.name!r} does not match skill name {bundle.name!r}")
    for rel, text in bundle.files.items():
        target = _safe_path(root, rel)
        if not target.is_file():
            problems.append(f"missing: {rel}")
        elif target.read_text(encoding="utf-8") != text:
            problems.append(f"stale: {rel}")
    for rel in _owned(root):
        if rel not in bundle.files:
            problems.append(f"unexpected: {rel}")
    return problems
